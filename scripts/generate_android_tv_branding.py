#!/usr/bin/env python3
"""Generate Android TV vector resources from the approved ZEON wordmark.

Run with Python 3 (standard library only):
  python scripts/generate_android_tv_branding.py
  python scripts/generate_android_tv_branding.py --check

The application minSdk is 24, which supports VectorDrawable gradients. The
banner remains a real 16:9 drawable on every supported API. TV-only mipmap
aliases select the square fallback/adaptive icon without changing phone icons.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/images/SVG/big-logo-dark.svg"
RES = ROOT / "android/app/src/main/res"
ANDROID = "http://schemas.android.com/apk/res/android"
AAPT = "http://schemas.android.com/aapt"
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("android", ANDROID)
ET.register_namespace("aapt", AAPT)


def attr(**values: object) -> dict[str, str]:
    return {f"{{{ANDROID}}}{key}": str(value) for key, value in values.items()}


def vector(width: int, height: int, viewport_width: int, viewport_height: int) -> ET.Element:
    return ET.Element("vector", attr(width=f"{width}dp", height=f"{height}dp",
                                    viewportWidth=viewport_width, viewportHeight=viewport_height))


def gradient_path(parent: ET.Element, data: str, start: tuple[float, float],
                  end: tuple[float, float], stops: list[tuple[str, str]]) -> None:
    path = ET.SubElement(parent, "path", attr(pathData=data))
    fill = ET.SubElement(path, f"{{{AAPT}}}attr", {"name": "android:fillColor"})
    gradient = ET.SubElement(fill, "gradient", attr(type="linear", startX=start[0],
                                                  startY=start[1], endX=end[0], endY=end[1]))
    for offset, color in stops:
        ET.SubElement(gradient, "item", attr(offset=offset, color=color))


def background(parent: ET.Element, width: int, height: int) -> None:
    # Graphite app neutrals; the logo retains the original green/lime accent.
    gradient_path(parent, f"M0,0 H{width} V{height} H0 Z", (0, 0), (width, height),
                  [("0", "#252730"), ("0.55", "#121316"), ("1", "#000000")])


def wordmark(parent: ET.Element, width: float, center_x: float, center_y: float) -> None:
    source = ET.parse(SOURCE).getroot()
    view = [float(value) for value in source.attrib["viewBox"].split()]
    if view != [0, 0, 346.67, 91.55]:
        raise ValueError("Review TV safe areas after changing the wordmark viewBox")
    scale = width / view[2]
    group = ET.SubElement(parent, "group", attr(
        scaleX=f"{scale:.9f}", scaleY=f"{scale:.9f}",
        translateX=f"{center_x - width / 2:.9f}",
        translateY=f"{center_y - view[3] * scale / 2:.9f}"))
    gradients = {node.attrib["id"]: node for node in source.findall(f".//{{{SVG}}}linearGradient")}
    artwork = source.find(f"{{{SVG}}}g")
    if artwork is None:
        raise ValueError("Expected the approved wordmark artwork group")
    for shape in artwork:
        if "transform" in shape.attrib:
            raise ValueError("Review transformed wordmark shapes before exporting")
        if shape.tag == f"{{{SVG}}}path":
            data = shape.attrib["d"]
        elif shape.tag == f"{{{SVG}}}rect":
            # Exact rounded-rectangle path, preserving the E's middle stroke.
            x, y, w, h = (float(shape.attrib[key]) for key in ("x", "y", "width", "height"))
            rx, ry = float(shape.get("rx", "0")), float(shape.get("ry", "0"))
            data = (f"M{x+rx},{y} H{x+w-rx} A{rx},{ry} 0 0 1 {x+w},{y+ry} "
                    f"V{y+h-ry} A{rx},{ry} 0 0 1 {x+w-rx},{y+h} "
                    f"H{x+rx} A{rx},{ry} 0 0 1 {x},{y+h-ry} "
                    f"V{y+ry} A{rx},{ry} 0 0 1 {x+rx},{y} Z")
        else:
            raise ValueError(f"Unsupported wordmark shape: {shape.tag}")
        fill = shape.attrib["fill"]
        if fill.startswith("url(#"):
            gradient = gradients[fill[5:-1]]
            if gradient.get("gradientUnits") != "userSpaceOnUse":
                raise ValueError("Expected absolute wordmark gradient coordinates")
            gradient_path(group, data,
                          (float(gradient.attrib["x1"]), float(gradient.attrib["y1"])),
                          (float(gradient.attrib["x2"]), float(gradient.attrib["y2"])),
                          [(stop.attrib["offset"], stop.attrib["stop-color"])
                           for stop in gradient])
        else:
            ET.SubElement(group, "path", attr(fillColor=fill, pathData=data))


def serialize(root: ET.Element) -> str:
    ET.indent(root, space="    ")
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/generate_android_tv_branding.py from\n'
            '     assets/images/SVG/big-logo-dark.svg. Do not edit by hand. -->\n'
            + ET.tostring(root, encoding="unicode") + "\n")


def resources() -> dict[Path, str]:
    banner = vector(160, 90, 320, 180)
    background(banner, 320, 180)
    wordmark(banner, 240, 160, 90)  # 40px side margins, full unmodified wordmark.
    legacy = vector(80, 80, 108, 108)
    background(legacy, 108, 108)
    wordmark(legacy, 64, 54, 54)  # Entire wordmark fits the adaptive safe zone.
    icon_background = vector(108, 108, 108, 108)
    background(icon_background, 108, 108)
    foreground = vector(108, 108, 108, 108)
    wordmark(foreground, 64, 54, 54)
    adaptive = ET.Element("adaptive-icon")
    ET.SubElement(adaptive, "background", attr(drawable="@drawable/ic_tv_icon_background"))
    ET.SubElement(adaptive, "foreground", attr(drawable="@drawable/ic_tv_icon_foreground"))
    aliases = ET.Element("resources")
    for name in ("ic_launcher", "ic_launcher_round"):
        ET.SubElement(aliases, "item", {"type": "mipmap", "name": name}).text = "@mipmap/ic_tv_icon"
    return {RES / name: serialize(resource) for name, resource in {
        "drawable/ic_tv_banner.xml": banner,
        "mipmap/ic_tv_icon.xml": legacy,
        "drawable/ic_tv_icon_background.xml": icon_background,
        "drawable/ic_tv_icon_foreground.xml": foreground,
        "mipmap-v26/ic_tv_icon.xml": adaptive,
        "values-television/tv_launcher_icons.xml": aliases,
    }.items()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in resources without writing")
    args = parser.parse_args()
    mismatches = []
    for path, expected in resources().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
        print(f"{'checked' if args.check else 'wrote'} {path.relative_to(ROOT)}")
    if mismatches:
        raise SystemExit("Stale TV resources: " + ", ".join(mismatches))


if __name__ == "__main__":
    main()
